// Builds supabase/migrations/010_seed_diagnostic_v2_question_bank.sql
// from the single source of truth in scripts/question-bank-v2.js
// (questions) and KNOWLEDGE_BASE/diagnostic/skill_map.json (metadata).
// Run: node scripts/build-diagnostic-v2-seed.js

const fs = require('fs');
const path = require('path');
const bank = require('./question-bank-v2');

function sqlStr(value) {
  return String(value).replace(/'/g, "''");
}

function validateBank() {
  const { test, questions } = bank;
  const errors = [];
  const countBySkill = {};

  if (!test.id || !test.title) errors.push('معلومات الاختبار ناقصة (id/title)');
  if (questions.length !== test.total_questions) {
    errors.push(
      `عدد الأسئلة ${questions.length} يخالف الكلي المعلن ${test.total_questions}`
    );
  }

  const ids = new Set();
  questions.forEach((q, i) => {
    if (!q.id) errors.push(`سؤال رقم ${i + 1} بدون id`);
    if (ids.has(q.id)) errors.push(`تكرار id: ${q.id}`);
    ids.add(q.id);

    if (!q.question) errors.push(`${q.id}: نص السؤال فارغ`);
    if (!Array.isArray(q.options) || q.options.length !== 4) {
      errors.push(`${q.id}: الخيارات يجب أن تكون 4`);
    } else {
      if (!q.options.some((o) => o.id === q.correct)) {
        errors.push(`${q.id}: الإجابة الصحيحة (${q.correct}) غير موجودة في الخيارات`);
      }
      if (q.options.filter((o) => o.diagnostic_error === null).length !== 1) {
        errors.push(`${q.id}: يجب وجود خيار صحيح واحد فقط (diagnostic_error === null)`);
      }
      for (const o of q.options) {
        if (!o.id || !o.text) errors.push(`${q.id}: أحد الخيارات ناقص (id أو نص)`);
        if (o.id !== q.correct && (typeof o.diagnostic_error !== 'string' || !o.diagnostic_error.trim())) {
          errors.push(`${q.id}: الخيار الخاطئ ${o.id} بدون diagnostic_error`);
        }
      }
    }
    if (![1, 2, 3, 4, 5].includes(q.difficulty)) {
      errors.push(`${q.id}: صعوبة غير صالحة (${q.difficulty})`);
    }
    if (!q.skill) errors.push(`${q.id}: بدون مهارة`);
    if (!q.explanation) errors.push(`${q.id}: بدون تفسير`);
    if (q.secondary_skill && !['A', 'B', 'C'].includes(q.category)) {
      errors.push(`${q.id}: category غير صالح`);
    }
    countBySkill[q.skill] = (countBySkill[q.skill] || 0) + 1;
  });

  return { errors, countBySkill };
}

function buildSql() {
  const { test } = bank;
  const lines = [];
  lines.push('-- ============================================================');
  lines.push('-- Migration 010: Seed diagnostic v2 question bank (bac-physics-v2)');
  lines.push('-- Generated by scripts/build-diagnostic-v2-seed.js — DO NOT EDIT.');
  lines.push('-- Source of truth: scripts/question-bank-v2.js');
  lines.push('-- ============================================================');
  lines.push('');

  lines.push('-- Retire the v1 bank: v2 becomes the active diagnostic test.');
  lines.push(`update public.diagnostic_tests set is_active = false where id = 'bac-physics-v1';`);
  lines.push('');

  lines.push(
    `insert into public.diagnostic_tests (id, title, description, subject, grade, version, question_bank_version, total_questions, time_limit_minutes, is_active)`
  );
  lines.push(`values (`);
  lines.push(`  '${sqlStr(test.id)}',`);
  lines.push(`  '${sqlStr(test.title)}',`);
  lines.push(`  '${sqlStr(test.description)}',`);
  lines.push(`  '${sqlStr(test.subject)}',`);
  lines.push(`  '${sqlStr(test.grade)}',`);
  lines.push(`  ${test.version},`);
  lines.push(`  '${sqlStr(test.question_bank_version)}',`);
  lines.push(`  ${test.total_questions},`);
  lines.push(`  ${test.time_limit_minutes},`);
  lines.push(`  true`);
  lines.push(`)`);
  lines.push(
    `on conflict (id) do update set title = excluded.title, description = excluded.description, version = excluded.version, question_bank_version = excluded.question_bank_version, total_questions = excluded.total_questions, time_limit_minutes = excluded.time_limit_minutes, is_active = excluded.is_active;`
  );
  lines.push('');

  for (const q of bank.questions) {
    const options = JSON.stringify(
      q.options.map((o) => ({ id: o.id, text: o.text, diagnostic_error: o.diagnostic_error || null }))
    );
    const tags = JSON.stringify(q.diagnostic_tags);
    const sec = q.secondary_skill ? `'${sqlStr(q.secondary_skill)}'` : 'null';
    const primary = `'${sqlStr(q.skill)}'`;
    const subSkill = `'${sqlStr(q.sub_skill || q.skill)}'`;

    lines.push(`insert into public.diagnostic_questions`);
    lines.push(
      `  (id, test_id, question_type, skill, primary_skill, secondary_skill, sub_skill, difficulty, question_text, options, correct_option, explanation, diagnostic_tags, weight)`
    );
    lines.push(`values (`);
    lines.push(`  '${sqlStr(q.id)}',`);
    lines.push(`  '${sqlStr(test.id)}',`);
    lines.push(`  '${sqlStr(q.question_type || 'single_choice')}',`);
    lines.push(`  '${sqlStr(q.skill)}',`);
    lines.push(`  ${primary},`);
    lines.push(`  ${sec},`);
    lines.push(`  ${subSkill},`);
    lines.push(`  ${q.difficulty},`);
    lines.push(`  '${sqlStr(q.question)}',`);
    lines.push(`  '${sqlStr(options)}'::jsonb,`);
    lines.push(`  '${sqlStr(q.correct)}',`);
    lines.push(`  '${sqlStr(q.explanation)}',`);
    lines.push(`  '${sqlStr(tags)}'::jsonb,`);
    lines.push(`  ${q.weight || 1}`);
    lines.push(`);`);
    lines.push('');
  }

  return lines.join('\n');
}

function main() {
  const { errors, countBySkill } = validateBank();
  if (errors.length) {
    console.error('خطأ في بنك الأسئلة:');
    errors.forEach((e) => console.error(' -', e));
    process.exit(1);
  }

  console.log('توزيع الأسئلة حسب المهارة:');
  Object.keys(countBySkill)
    .sort()
    .forEach((s) => console.log('  ', s, '=', countBySkill[s]));

  const sql = buildSql();
  const out = path.join(__dirname, '..', 'supabase', 'migrations', '010_seed_diagnostic_v2_question_bank.sql');
  fs.writeFileSync(out, sql, 'utf8');
  console.log('\nتم إنشاء:', out, `(${sql.length} حرف)`);
}

main();