// Shuffles diagnostic v2 options deterministically and idempotently.
//  1. Rewrites scripts/question-bank-v2.js with the shuffled option order
//     (canonical source for all downstream consumers).
//  2. Generates supabase/migrations/011_shuffle_v2_options.sql to bring the
//     already-seeded DB (migration 010 applied unshuffled) in line.
//
// Canonical order is a PURE FUNCTION of each question's data:
//   perm(seed(id)) applied to options sorted by text.
// Re-running produces identical output regardless of current order.
// Run: node scripts/build-diagnostic-v2-shuffle.js
const fs = require('fs');
const path = require('path');

const SALT = 'bac-physics-v2-shuffle-2026';
const LETTERS = ['A', 'B', 'C', 'D'];

function hashString(str) {
  let h = 1779033703 ^ str.length;
  for (let i = 0; i < str.length; i++) {
    h = Math.imul(h ^ str.charCodeAt(i), 3432918353);
    h = (h << 13) | (h >>> 19);
  }
  h = Math.imul(h ^ (h >>> 16), 2246822507);
  h = Math.imul(h ^ (h >>> 13), 3266489909);
  return (h ^= h >>> 16) >>> 0;
}

function mulberry32(a) {
  return function () {
    let t = (a += 0x6d2b79f5);
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function permute(seed) {
  const rand = mulberry32(seed);
  const arr = [0, 1, 2, 3];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

function canonicalOrder(q) {
  // Baseline: options sorted by text (ties broken by original position).
  const baseline = q.options
    .map((o, i) => ({ o, i }))
    .sort((a, b) => {
      const c = a.o.text.localeCompare(b.o.text);
      return c !== 0 ? c : a.i - b.i;
    })
    .map((x) => x.i);

  const perm = permute(hashString(SALT + '|' + q.id));
  const order = perm.map((k) => baseline[k]); // source indices in canonical A..D positions

  const srcIdxOfCorrect = q.options.findIndex((o) => o.id === q.correct);
  const correctPosition = order.indexOf(srcIdxOfCorrect);

  const options = order.map((srcIndex, k) => ({
    id: LETTERS[k],
    text: q.options[srcIndex].text,
    diagnostic_error: q.options[srcIndex].diagnostic_error
  }));
  return { options, correct: LETTERS[correctPosition] };
}

function main() {
  const bank = require('./question-bank-v2');

  const stats = { A: 0, B: 0, C: 0, D: 0 };
  let changed = 0;
  const questions = bank.questions.map((q) => {
    const can = canonicalOrder(q);
    const changedNow =
      JSON.stringify(can.options) !== JSON.stringify(q.options) || can.correct !== q.correct;
    if (changedNow) changed++;
    stats[can.correct]++;
    const clone = JSON.parse(JSON.stringify(q));
    clone.options = can.options;
    clone.correct = can.correct;
    return clone;
  });

  // Idempotency guard: deriving canonical from the just-built output must be a no-op.
  const ids = new Set();
  for (const q of questions) {
    if (ids.has(q.id)) throw new Error('تكرار id!');
    ids.add(q.id);
    const re = canonicalOrder(q);
    if (JSON.stringify(re.options) !== JSON.stringify(q.options) || re.correct !== q.correct) {
      throw new Error(`غير مستقر: ${q.id}`);
    }
  }

  const shuffledBank = { test: bank.test, questions };

  const header = `// ============================================================
// Diagnostic v2 question bank — اختبار تحديد المستوى التشخيصي
// (نظام bac-physics-v2) لتلاميذ البكالوريا الجزائرية.
//
// Generated by scripts/build-diagnostic-v2-shuffle.js — option order is a
// deterministic, idempotent permutation (see script). Migration 011
// reconciles the seeded DB with this canonical source.
// Source of truth for all downstream consumers in this repo.
//
// Design rules (approved report):
//   * 50 أسئلة QCM، 5 مستويات صعوبة (L1..L5)
//   * لا يختبر أي مفهوم من دروس السنة الحالية:
//     أي قانون "يستحضر" السنة الحالية يُعطى داخل نص السؤال.
//   * كل مهارة في skill_map.json تُقاس بسؤالين على الأقل.
//   * كل خيار خاطئ يحمل diagnostic_error (تحليل الأخطاء).
// ============================================================

module.exports = 
`;
  const sourcePath = path.join(__dirname, 'question-bank-v2.js');
  fs.writeFileSync(sourcePath, header + JSON.stringify(shuffledBank, null, 2) + '\n', 'utf8');

  const sqlLines = [
    '-- ============================================================',
    '-- Migration 011: Shuffle diagnostic v2 question options.',
    '-- Generated by scripts/build-diagnostic-v2-shuffle.js — DO NOT EDIT.',
    '-- Absolute set: brings the migration-010 seeded rows (authored order)',
    '-- to the canonical order defined by the shuffle script.',
    '-- ============================================================',
    ''
  ];
  for (const q of questions) {
    const options = JSON.stringify(
      q.options.map((o) => ({ id: o.id, text: o.text, diagnostic_error: o.diagnostic_error || null }))
    );
    sqlLines.push(`update public.diagnostic_questions`);
    sqlLines.push(`set options = '${options.replace(/'/g, "''")}'::jsonb, correct_option = '${q.correct}'`);
    sqlLines.push(`where id = '${q.id}';`);
    sqlLines.push('');
  }

  const sqlPath = path.join(__dirname, '..', 'supabase', 'migrations', '011_shuffle_v2_options.sql');
  fs.writeFileSync(sqlPath, sqlLines.join('\n'), 'utf8');

  console.log('مواضع الإجابة الصحيحة بعد التبديل:', JSON.stringify(stats));
  console.log('أسئلة تغيّرت: ', changed, 'من', questions.length);
  console.log('تم تحديث:', sourcePath);
  console.log('تم إنشاء:', sqlPath, `(${sqlLines.join('\n').length} حرف)`);
}

main();